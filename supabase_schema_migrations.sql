-- supabase_schema_migrations.sql — פנקס המיגרציות שהורצו
--
-- להריץ ב-Supabase SQL Editor. בטוח להריץ יותר מפעם אחת (idempotent).
--
-- בריפו יש ~17 קבצי SQL, כל אחד אידמפוטנטי, והתיעוד היחיד של מה שבאמת הורץ היה
-- הזיכרון. הביקורת של יולי כבר תפסה תוצאה אחת של זה:
-- supabase/migrations/20260609_multi_tenant.sql מעולם לא הורץ ומפנה לטבלאות
-- שלא קיימות. שחרור קוד שתלוי במיגרציה שלא הורצה הוא תקלת ייצור ששום בדיקה
-- לא תופסת, כי הבדיקות רצות מול DB שבו מישהו במקרה הריץ את ה-SQL.
--
-- הטבלה הזו לא **מריצה** כלום — DDL דורש חיבור מורשה, ו-RPC שמריץ SQL שרירותי
-- היה חור גרוע בהרבה מהבעיה שהוא פותר. היא רושמת מה הורץ, כדי ש-`npm run ship`
-- יסרב לשחרר קוד שהמיגרציה שלו עדיין ממתינה.
-- ============================================================================

CREATE TABLE IF NOT EXISTS schema_migrations (
  name       text PRIMARY KEY,
  sha256     text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now(),
  applied_by text,
  note       text
);

-- מטא-דאטה של פריסה, לא נתוני דייר: RLS פעיל בלי מדיניות = חסום לכל משתמש קצה.
ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY;

